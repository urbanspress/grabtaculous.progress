package container

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

var rePlaceholder = regexp.MustCompile(`\$\{([A-Za-z_][A-Za-z0-9_]*)(?::([?-])([^}]*))?\}`)

// RenderComposeYAML validates stack hardening (GRABTAC-E401) and emits deterministic Compose YAML.
func RenderComposeYAML(stack StackSpec) ([]byte, error) {
	if err := ValidateStackSpec(stack, AuditOptions{RequireDigest: true}); err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("# Hardened --read-only Docker Compose stack generated by Grabtaculous v0.1.0\n")
	if strings.TrimSpace(stack.StackName) != "" {
		fmt.Fprintf(&b, "# Stack: %s\n", strings.TrimSpace(stack.StackName))
	}
	b.WriteString("services:\n")

	for _, svc := range stack.Services {
		writeServiceYAML(&b, svc)
	}

	b.WriteString("\nnetworks:\n")
	b.WriteString("  grabtac_loopback:\n")
	b.WriteString("    driver: bridge\n")
	b.WriteString("  grabtac_internal:\n")
	b.WriteString("    driver: bridge\n")
	b.WriteString("    internal: true\n")

	vols := collectNamedVolumes(stack)
	if len(vols) > 0 {
		b.WriteString("\nvolumes:\n")
		for _, v := range vols {
			fmt.Fprintf(&b, "  %s:\n", v)
		}
	}

	return []byte(b.String()), nil
}

func writeServiceYAML(b *strings.Builder, svc ServiceSpec) {
	fmt.Fprintf(b, "  %s:\n", svc.Name)
	fmt.Fprintf(b, "    image: %s\n", svc.Image)
	if strings.TrimSpace(svc.Container) != "" {
		fmt.Fprintf(b, "    container_name: %s\n", strings.TrimSpace(svc.Container))
	}
	b.WriteString("    read_only: true\n")
	fmt.Fprintf(b, "    user: %q\n", svc.User)
	b.WriteString("    cap_drop:\n")
	b.WriteString("      - ALL\n")
	b.WriteString("    security_opt:\n")
	b.WriteString("      - no-new-privileges:true\n")

	tmpfsList := svc.Tmpfs
	if len(tmpfsList) == 0 {
		tmpfsList = []string{"/tmp:rw,noexec,nosuid,size=64m"}
	}
	b.WriteString("    tmpfs:\n")
	for _, t := range tmpfsList {
		fmt.Fprintf(b, "      - %s\n", t)
	}

	if len(svc.Ports) > 0 {
		b.WriteString("    ports:\n")
		for _, p := range svc.Ports {
			fmt.Fprintf(b, "      - %q\n", p)
		}
	}

	if strings.TrimSpace(svc.WorkingDir) != "" {
		fmt.Fprintf(b, "    working_dir: %s\n", strings.TrimSpace(svc.WorkingDir))
	}

	if len(svc.Volumes) > 0 {
		b.WriteString("    volumes:\n")
		for _, v := range svc.Volumes {
			fmt.Fprintf(b, "      - %s\n", v)
		}
	}

	nets := svc.Networks
	if len(nets) == 0 {
		if svc.IsDataStore {
			nets = []string{"grabtac_internal"}
		} else {
			nets = []string{"grabtac_loopback", "grabtac_internal"}
		}
	}
	b.WriteString("    networks:\n")
	for _, n := range nets {
		fmt.Fprintf(b, "      - %s\n", n)
	}

	if len(svc.Environment) > 0 {
		keys := make([]string, 0, len(svc.Environment))
		for k := range svc.Environment {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		b.WriteString("    environment:\n")
		for _, k := range keys {
			fmt.Fprintf(b, "      %s: %q\n", k, svc.Environment[k])
		}
	}

	if len(svc.Command) > 0 {
		b.WriteString("    command:\n")
		for _, arg := range svc.Command {
			fmt.Fprintf(b, "      - %q\n", arg)
		}
	}

	if svc.Healthcheck != nil && len(svc.Healthcheck.Test) > 0 {
		b.WriteString("    healthcheck:\n")
		b.WriteString("      test:\n")
		for _, t := range svc.Healthcheck.Test {
			fmt.Fprintf(b, "        - %q\n", t)
		}
		if svc.Healthcheck.Interval != "" {
			fmt.Fprintf(b, "      interval: %s\n", svc.Healthcheck.Interval)
		}
		if svc.Healthcheck.Timeout != "" {
			fmt.Fprintf(b, "      timeout: %s\n", svc.Healthcheck.Timeout)
		}
		if svc.Healthcheck.Retries > 0 {
			fmt.Fprintf(b, "      retries: %d\n", svc.Healthcheck.Retries)
		}
		if svc.Healthcheck.StartPeriod != "" {
			fmt.Fprintf(b, "      start_period: %s\n", svc.Healthcheck.StartPeriod)
		}
	}

	restart := strings.TrimSpace(svc.Restart)
	if restart == "" {
		restart = "unless-stopped"
	}
	fmt.Fprintf(b, "    restart: %s\n", restart)
}

func collectNamedVolumes(stack StackSpec) []string {
	set := map[string]struct{}{}
	for _, v := range stack.Volumes {
		if trimmed := strings.TrimSpace(v); trimmed != "" {
			set[trimmed] = struct{}{}
		}
	}
	for _, svc := range stack.Services {
		for _, vol := range svc.Volumes {
			parts := strings.SplitN(strings.TrimSpace(vol), ":", 2)
			if len(parts) == 2 {
				src := strings.TrimSpace(parts[0])
				if src != "" && !strings.HasPrefix(src, ".") && !strings.HasPrefix(src, "/") {
					set[src] = struct{}{}
				}
			}
		}
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// RenderEnvExample generates a placeholder-only deploy/.env.example containing zero real secrets.
func RenderEnvExample(stack StackSpec) []byte {
	vars := map[string]string{}
	collectFromStr := func(s string) {
		for _, m := range rePlaceholder.FindAllStringSubmatch(s, -1) {
			name := m[1]
			op := m[2]
			def := m[3]
			if _, exists := vars[name]; exists {
				continue
			}
			if op == "-" && def != "" && !reSecretKey.MatchString(name) {
				vars[name] = def
			} else {
				vars[name] = "<set-via-secret-manager>"
			}
		}
	}

	for _, svc := range stack.Services {
		collectFromStr(svc.Image)
		for _, p := range svc.Ports {
			collectFromStr(p)
		}
		for _, v := range svc.Environment {
			collectFromStr(v)
		}
		for _, c := range svc.Command {
			collectFromStr(c)
		}
	}

	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Grabtaculous v0.1.0 Environment Template — supply real secrets via secret manager or untracked .env.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s=%s\n", k, vars[k])
	}
	return []byte(b.String())
}
