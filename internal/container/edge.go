package container

import (
	"fmt"
	"net"
	"regexp"
	"strings"

	"grabtaculous/internal/safepath"
)

var reSafeDomain = regexp.MustCompile(`^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$`)

// EdgeRouteConfig defines automatic edge TLS routing to loopback Grisp/container upstreams.
type EdgeRouteConfig struct {
	EdgeProxy          string `json:"edge_proxy"`
	Domain             string `json:"domain"`
	UpstreamHost       string `json:"upstream_host"`
	UpstreamPorts      []int  `json:"upstream_ports"`
	HealthPath         string `json:"health_path"`
	StaticAlias        string `json:"static_alias,omitempty"`
	StaticRoot         string `json:"static_root,omitempty"`
	EnableOnDemandTLS  bool   `json:"enable_on_demand_tls,omitempty"`
	CloudflareTunnelID string `json:"cloudflare_tunnel_id,omitempty"`
}

// EdgeArtifact captures the generated reverse-proxy configuration file.
type EdgeArtifact struct {
	Provider string `json:"provider"`
	Filename string `json:"filename"`
	Content  []byte `json:"-"`
}

// RenderEdgeConfig validates loopback-only upstreams and renders Caddy, Nginx, or Cloudflare Tunnel config.
func RenderEdgeConfig(cfg EdgeRouteConfig) (*EdgeArtifact, error) {
	provider := strings.ToLower(strings.TrimSpace(cfg.EdgeProxy))
	if provider == "" {
		provider = "caddy"
	}
	domain := strings.TrimSpace(cfg.Domain)
	if domain == "" {
		domain = "localhost"
	}
	if !reSafeDomain.MatchString(domain) {
		return nil, safepath.NewError(
			safepath.ErrSecurityPolicy,
			fmt.Sprintf("unsafe edge domain %q", cfg.Domain),
			"Provide a valid hostname or domain name without spaces or control characters.",
		)
	}

	host := strings.TrimSpace(cfg.UpstreamHost)
	if host == "" {
		host = "127.0.0.1"
	}
	if !isLoopbackHost(host) {
		return nil, safepath.NewError(
			safepath.ErrSecurityPolicy,
			fmt.Sprintf("edge upstream host %q must be loopback (127.0.0.1 or ::1) per ADR-005", host),
			"Bind app workers and containers strictly to 127.0.0.1.",
		)
	}

	if len(cfg.UpstreamPorts) == 0 {
		return nil, safepath.NewError(safepath.ErrSecurityPolicy, "at least one upstream port is required", "Allocate loopback ports in 127.0.0.1:8765-8772.")
	}
	for _, p := range cfg.UpstreamPorts {
		if p < 1 || p > 65535 {
			return nil, safepath.NewError(safepath.ErrSecurityPolicy, fmt.Sprintf("invalid upstream port %d", p), "Use valid TCP port numbers 1-65535.")
		}
	}

	healthPath := strings.TrimSpace(cfg.HealthPath)
	if healthPath == "" {
		healthPath = "/_ready"
	}
	if !strings.HasPrefix(healthPath, "/") || strings.ContainsAny(healthPath, " \t\r\n;{}") {
		return nil, safepath.NewError(safepath.ErrSecurityPolicy, fmt.Sprintf("invalid health check path %q", healthPath), "Use a clean path such as /_ready.")
	}

	switch provider {
	case "caddy":
		return &EdgeArtifact{
			Provider: "caddy",
			Filename: "deploy/Caddyfile",
			Content:  renderCaddyfile(domain, host, cfg.UpstreamPorts, healthPath, cfg.EnableOnDemandTLS),
		}, nil
	case "nginx":
		return &EdgeArtifact{
			Provider: "nginx",
			Filename: "deploy/nginx.conf",
			Content:  renderNginxConf(domain, host, cfg.UpstreamPorts),
		}, nil
	case "cloudflare-tunnel":
		return &EdgeArtifact{
			Provider: "cloudflare-tunnel",
			Filename: "deploy/cloudflared.yml",
			Content:  renderCloudflaredYAML(domain, host, cfg.UpstreamPorts, cfg.CloudflareTunnelID),
		}, nil
	default:
		return nil, safepath.NewError(
			safepath.ErrSecurityPolicy,
			fmt.Sprintf("unsupported edge proxy %q (expected caddy, nginx, or cloudflare-tunnel)", cfg.EdgeProxy),
			"Select caddy (recommended), nginx, or cloudflare-tunnel.",
		)
	}
}

func isLoopbackHost(host string) bool {
	if strings.EqualFold(host, "localhost") {
		return true
	}
	ip := net.ParseIP(strings.Trim(host, "[]"))
	return ip != nil && ip.IsLoopback()
}

func formatUpstreamAddr(host string, port int) string {
	if strings.Contains(host, ":") && !strings.HasPrefix(host, "[") {
		return fmt.Sprintf("[%s]:%d", host, port)
	}
	return fmt.Sprintf("%s:%d", host, port)
}

func renderCaddyfile(domain, host string, ports []int, healthPath string, onDemand bool) []byte {
	upstreams := make([]string, 0, len(ports))
	for _, p := range ports {
		upstreams = append(upstreams, formatUpstreamAddr(host, p))
	}

	var b strings.Builder
	b.WriteString("# Automatic HTTPS Caddyfile generated by Grabtaculous v1.0.0 (ADR-005 / --trusted-proxy 127.0.0.1)\n")
	if onDemand {
		b.WriteString("{\n  on_demand_tls {\n    ask http://127.0.0.1:9440/_health\n  }\n}\n\n")
	}
	fmt.Fprintf(&b, "%s {\n", domain)
	b.WriteString("  encode zstd gzip\n")
	b.WriteString("  header {\n")
	b.WriteString("    X-Content-Type-Options nosniff\n")
	b.WriteString("    Referrer-Policy strict-origin-when-cross-origin\n")
	b.WriteString("  }\n")
	if onDemand {
		b.WriteString("  tls {\n    on_demand\n  }\n")
	}
	fmt.Fprintf(&b, "  reverse_proxy %s {\n", strings.Join(upstreams, " "))
	b.WriteString("    lb_policy least_conn\n")
	fmt.Fprintf(&b, "    health_uri %s\n", healthPath)
	b.WriteString("    health_interval 5s\n")
	b.WriteString("    health_timeout 2s\n")
	b.WriteString("    health_status 200\n")
	b.WriteString("    header_up X-Forwarded-Proto {scheme}\n")
	b.WriteString("    header_up X-Real-IP {remote_host}\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return []byte(b.String())
}

func renderNginxConf(domain, host string, ports []int) []byte {
	var b strings.Builder
	b.WriteString("# Nginx 1.30.6 (Stable) + Certbot ACME configuration generated by Grabtaculous v1.1.0 (ADR-005 / --trusted-proxy 172.16.0.0/12,127.0.0.1)\n")
	b.WriteString("upstream grabtac_upstreams {\n")
	b.WriteString("  least_conn;\n")
	for _, p := range ports {
		fmt.Fprintf(&b, "  server %s max_fails=2 fail_timeout=5s;\n", formatUpstreamAddr(host, p))
	}
	b.WriteString("  keepalive 192;\n")
	b.WriteString("  keepalive_requests 10000;\n")
	b.WriteString("  keepalive_timeout 60s;\n")
	b.WriteString("}\n\n")
	b.WriteString("server {\n")
	b.WriteString("  listen 80;\n")
	b.WriteString("  listen [::]:80;\n")
	fmt.Fprintf(&b, "  server_name %s;\n", domain)
	b.WriteString("  location /.well-known/acme-challenge/ {\n")
	b.WriteString("    root /var/www/certbot;\n")
	b.WriteString("  }\n")
	b.WriteString("  location / {\n")
	b.WriteString("    return 301 https://$host$request_uri;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
	b.WriteString("server {\n")
	b.WriteString("  listen 443 quic reuseport;\n")
	b.WriteString("  listen [::]:443 quic reuseport;\n")
	b.WriteString("  listen 443 ssl;\n")
	b.WriteString("  listen [::]:443 ssl;\n")
	b.WriteString("  http2 on;\n")
	fmt.Fprintf(&b, "  server_name %s;\n", domain)
	fmt.Fprintf(&b, "  ssl_certificate /etc/letsencrypt/live/%s/fullchain.pem;\n", domain)
	fmt.Fprintf(&b, "  ssl_certificate_key /etc/letsencrypt/live/%s/privkey.pem;\n", domain)
	b.WriteString("  quic_retry on;\n")
	b.WriteString("  quic_gso on;\n")
	b.WriteString("  ssl_early_data off;\n")
	b.WriteString("  add_header Alt-Svc 'h3=\":443\"; ma=86400' always;\n")
	b.WriteString("  add_header X-Content-Type-Options nosniff always;\n")
	b.WriteString("  add_header Referrer-Policy strict-origin-when-cross-origin always;\n")
	b.WriteString("  location / {\n")
	b.WriteString("    proxy_pass http://grabtac_upstreams;\n")
	b.WriteString("    proxy_http_version 1.1;\n")
	b.WriteString("    proxy_set_header Connection \"\";\n")
	b.WriteString("    proxy_next_upstream error timeout http_502 http_503 http_504;\n")
	b.WriteString("    proxy_set_header Host $host;\n")
	b.WriteString("    proxy_set_header X-Real-IP $remote_addr;\n")
	b.WriteString("    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
	b.WriteString("    proxy_set_header X-Forwarded-Proto $scheme;\n")
	b.WriteString("    proxy_set_header X-Forwarded-Host $host;\n")
	b.WriteString("    proxy_buffer_size 16k;\n")
	b.WriteString("    proxy_buffers 16 32k;\n")
	b.WriteString("    proxy_max_temp_file_size 0;\n")
	b.WriteString("  }\n")
	b.WriteString("  location ^~ /_protected_media/ {\n")
	b.WriteString("    internal;\n")
	b.WriteString("    alias /var/lib/grisp/uploads/;\n")
	b.WriteString("    sendfile on;\n")
	b.WriteString("    aio threads;\n")
	b.WriteString("    directio 8m;\n")
	b.WriteString("    output_buffers 2 1m;\n")
	b.WriteString("    gzip off;\n")
	b.WriteString("    limit_rate_after 20m;\n")
	b.WriteString("    limit_rate 12m;\n")
	b.WriteString("    add_header X-Content-Type-Options nosniff always;\n")
	b.WriteString("  }\n")
	b.WriteString("  location ~ ^/_protected_b2/([^/]+)/(.+)$ {\n")
	b.WriteString("    internal;\n")
	b.WriteString("    resolver 1.1.1.1 8.8.8.8 valid=300s ipv6=off;\n")
	b.WriteString("    set $b2_host $1;\n")
	b.WriteString("    set $b2_path $2;\n")
	b.WriteString("    proxy_http_version 1.1;\n")
	b.WriteString("    proxy_set_header Host $b2_host;\n")
	b.WriteString("    proxy_set_header Connection \"\";\n")
	b.WriteString("    proxy_hide_header x-amz-id-2;\n")
	b.WriteString("    proxy_hide_header x-amz-request-id;\n")
	b.WriteString("    proxy_hide_header x-bz-file-id;\n")
	b.WriteString("    proxy_hide_header x-bz-file-name;\n")
	b.WriteString("    proxy_hide_header x-bz-content-sha1;\n")
	b.WriteString("    proxy_ssl_server_name on;\n")
	b.WriteString("    proxy_buffering off;\n")
	b.WriteString("    proxy_max_temp_file_size 0;\n")
	b.WriteString("    gzip off;\n")
	b.WriteString("    limit_rate_after 20m;\n")
	b.WriteString("    limit_rate 12m;\n")
	b.WriteString("    proxy_pass https://$b2_host/$b2_path$is_args$args;\n")
	b.WriteString("  }\n")
	b.WriteString("  location ~ ^/_(health|ready)$ {\n")
	b.WriteString("    allow 127.0.0.1;\n")
	b.WriteString("    allow ::1;\n")
	b.WriteString("    deny all;\n")
	b.WriteString("    proxy_pass http://grabtac_upstreams;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return []byte(b.String())
}

func renderCloudflaredYAML(domain, host string, ports []int, tunnelID string) []byte {
	id := strings.TrimSpace(tunnelID)
	if id == "" {
		id = "${CLOUDFLARE_TUNNEL_ID}"
	}
	var b strings.Builder
	b.WriteString("# Cloudflare Tunnel zero-inbound-port configuration generated by Grabtaculous v1.0.0\n")
	fmt.Fprintf(&b, "tunnel: %s\n", id)
	b.WriteString("credentials-file: /etc/cloudflared/credentials.json\n")
	b.WriteString("ingress:\n")
	fmt.Fprintf(&b, "  - hostname: %s\n", domain)
	fmt.Fprintf(&b, "    service: http://%s\n", formatUpstreamAddr(host, ports[0]))
	b.WriteString("    originRequest:\n")
	fmt.Fprintf(&b, "      httpHostHeader: %s\n", domain)
	b.WriteString("  - service: http_status:404\n")
	return []byte(b.String())
}
